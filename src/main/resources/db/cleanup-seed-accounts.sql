-- 联调/演示种子账号清理（后端测试报告 P1 风险项：18 个公开口令账号暴露在公网）
--
-- 背景：data-seed.sql 的 18 个测试账号使用公开口令（900001/Admin@123、800101/Sec@12345、
-- 700101/Tea@12345、20230101/Stu@12345、600001/Sup@12345 …），其中 8 个 status=1 可直接登录。
-- 公网环境（如 https://textbooksorder.moonzj.com）保留这些账号 = 任何人可拿到超管权限。
-- 本脚本用于「联调结束 → 正式投用」之间的一次性清理，幂等、可重复执行。
--
-- 口径选择：**停用**而非删除。
--   * 停用（本脚本默认）：账号不再能登录（status=0），且 role_version+1 + 撤销全部 refresh
--     让已签发的令牌立刻失效；审计日志/导出记录里「谁在什么时候做了什么」的历史留痕不受影响。
--   * 删除（见文件末尾的可选段）：会留下悬空的 created_by / review_by 等引用，审计链断裂，
--     非必要不要用。若确需删除，请先备份。
--
-- 使用方式（在数据库服务器上执行，注意用有写权限的运维账号，而非只读的应用账号 textbook_app）：
--   mysql -u root -p textbook_order < cleanup-seed-accounts.sql
-- 执行后校验（应为 0）：
--   SELECT COUNT(*) FROM sys_user WHERE deleted = 0 AND status = 1 AND user_no IN (
--     '900001','900002','900003','800101','800102','800103','700101','700102','700103',
--     '700201','700202','20230101','20230102','20230103','20230201','600001','600002','600003');
-- 真实账号（导入生成的学号/工号）不在清理范围内，不受影响。
-- ============================================================================
SET NAMES utf8mb4;

-- 1) 停用账号（幂等：已是 status=0 的不再重复累加 role_version）
UPDATE sys_user
SET status = 0,
    role_version = role_version + 1,
    updated_at = NOW(3)
WHERE deleted = 0
  AND status = 1
  AND user_no IN (
      '900001', '900002', '900003',          -- ADMIN
      '800101', '800102', '800103',          -- SECRETARY
      '700101', '700102', '700103',          -- TEACHER
      '700201', '700202',
      '20230101', '20230102', '20230103',    -- STUDENT
      '20230201',
      '600001', '600002', '600003'           -- SUPPLIER
  );

-- 2) 撤销这些账号的全部 refresh 令牌（清场后即使浏览器里还留着 refreshToken 也无法续期）
UPDATE sys_user_token t
JOIN sys_user u ON u.id = t.user_id
SET t.revoked = 1, t.updated_at = NOW(3)
WHERE t.revoked = 0
  AND t.deleted = 0
  AND u.user_no IN (
      '900001', '900002', '900003', '800101', '800102', '800103', '700101', '700102',
      '700103', '700201', '700202', '20230101', '20230102', '20230103', '20230201',
      '600001', '600002', '600003'
  );

-- 3) 学期归属置「不在册」（否则这些账号仍会出现在名单/导出与「未授权兜底名单」里）
UPDATE user_semester_profile p
JOIN sys_user u ON u.id = p.user_id
SET p.status = 0, p.updated_at = NOW(3)
WHERE p.deleted = 0
  AND u.user_no IN (
      '900001', '900002', '900003', '800101', '800102', '800103', '700101', '700102',
      '700103', '700201', '700202', '20230101', '20230102', '20230103', '20230201',
      '600001', '600002', '600003'
  );

